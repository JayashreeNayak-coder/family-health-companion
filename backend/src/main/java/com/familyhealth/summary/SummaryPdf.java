package com.familyhealth.summary;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.time.LocalDate;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import com.familyhealth.records.SourceType;
import com.familyhealth.summary.SummaryDtos.Conflict;
import com.familyhealth.summary.SummaryDtos.Point;
import com.familyhealth.summary.SummaryDtos.Response;
import com.familyhealth.summary.SummaryDtos.Source;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDDocumentInformation;
import org.apache.pdfbox.pdmodel.PDPage;
import org.apache.pdfbox.pdmodel.PDPageContentStream;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.pdmodel.font.PDType0Font;

/**
 * Lays out a summary as an A4 PDF (Phase 18, docs/02 section 3.10). Every page carries the label
 * that this is a user-generated, AI-generated record summary and not a medical certificate.
 * Plain text only: nothing in a summary is interpreted as markup.
 */
final class SummaryPdf {

	static final String LABEL = "User-generated health record summary. Not an official medical certificate.";

	private static final DateTimeFormatter DATE = DateTimeFormatter.ofPattern("d MMM yyyy", Locale.ENGLISH);

	private static final Map<String, String> TOPICS = new LinkedHashMap<>();

	private static final Map<String, String> TYPES = Map.of("CONDITION", "Condition", "ALLERGY", "Allergy",
			"MEDICATION", "Medication", "LAB_RESULT", "Lab result", "VISIT", "Visit", "SYMPTOM", "Symptom");

	static {
		TOPICS.put("CONDITIONS", "Conditions");
		TOPICS.put("ALLERGIES", "Allergies");
		TOPICS.put("MEDICATIONS", "Medications");
		TOPICS.put("LAB_RESULTS", "Lab results");
		TOPICS.put("VISITS", "Visits");
		TOPICS.put("SYMPTOMS", "Symptoms");
	}

	private static final float MARGIN = 56;

	private static final float FOOTER = 48;

	private static final byte[] REGULAR = font("NotoSans-Regular.ttf");

	private static final byte[] BOLD = font("NotoSans-Bold.ttf");

	private final PDDocument document = new PDDocument();

	private final PDType0Font regular;

	private final PDType0Font bold;

	private final Map<PDType0Font, Map<Integer, Boolean>> glyphs = new HashMap<>();

	private final List<PDPage> pages = new ArrayList<>();

	private PDPageContentStream stream;

	private float y;

	private SummaryPdf() throws IOException {
		regular = PDType0Font.load(document, new ByteArrayInputStream(REGULAR), true);
		bold = PDType0Font.load(document, new ByteArrayInputStream(BOLD), true);
	}

	static byte[] render(Response summary, String profileName) {
		try {
			SummaryPdf pdf = new SummaryPdf();
			try {
				return pdf.write(summary, profileName);
			}
			finally {
				pdf.document.close();
			}
		}
		catch (IOException ex) {
			throw new UncheckedIOException("The PDF couldn't be made", ex);
		}
	}

	private byte[] write(Response summary, String profileName) throws IOException {
		PDDocumentInformation info = document.getDocumentInformation();
		info.setTitle("Health record summary");
		info.setSubject(LABEL);

		newPage();
		text(bold, 20, "Health record summary", 0);
		gap(4);
		text(bold, 13, profileName, 0);
		text(regular, 10, "Period: " + period(summary.periodFrom(), summary.periodTo()), 0);
		text(regular, 10, "Made on " + DATE.format(summary.createdAt().atZone(ZoneOffset.UTC)) + " (UTC). AI-generated by "
				+ summary.model() + ", prompt " + summary.promptVersion() + ".", 0);
		gap(8);
		text(bold, 10, LABEL, 0);
		text(regular, 10, summary.disclaimer(), 0);

		Map<String, List<Point>> byTopic = new LinkedHashMap<>();
		for (Point point : summary.points()) {
			byTopic.computeIfAbsent(point.topic(), ignored -> new ArrayList<>()).add(point);
		}
		for (Map.Entry<String, List<Point>> topic : byTopic.entrySet()) {
			heading(TOPICS.getOrDefault(topic.getKey(), "Other"));
			for (Point point : topic.getValue()) {
				bullet(point.text());
				for (Source source : point.sources()) {
					text(regular, 9, "Source: " + source(source), 14);
				}
				gap(4);
			}
		}
		if (summary.points().isEmpty()) {
			heading("Summary");
			text(regular, 10, "No statements were made from the records in this period.", 0);
		}
		if (!summary.conflicts().isEmpty()) {
			heading("Records that disagree");
			for (Conflict conflict : summary.conflicts()) {
				bullet(conflict.text());
				for (Source source : conflict.sources()) {
					text(regular, 9, "Source: " + source(source), 14);
				}
				gap(4);
			}
		}
		list("Missing information", summary.gaps());
		list("Limitations", summary.limitations());

		stream.close();
		footers();
		ByteArrayOutputStream out = new ByteArrayOutputStream();
		document.save(out);
		return out.toByteArray();
	}

	private void list(String title, List<String> lines) throws IOException {
		if (lines.isEmpty()) {
			return;
		}
		heading(title);
		for (String line : lines) {
			bullet(line);
		}
	}

	private static String period(LocalDate from, LocalDate to) {
		if (from == null && to == null) {
			return "all dates";
		}
		return (from == null ? "the earliest record" : DATE.format(from)) + " to "
				+ (to == null ? "the latest record" : DATE.format(to));
	}

	private static String source(Source source) {
		List<String> parts = new ArrayList<>();
		parts.add(TYPES.getOrDefault(source.type(), "Record"));
		parts.add(source.date() == null ? "date unknown" : DATE.format(source.date()));
		parts.add(source.title());
		if (source.detail() != null && !source.detail().isBlank()) {
			parts.add(source.detail());
		}
		if (source.sourceType() != null) {
			parts.add(source.sourceType() == SourceType.DOCUMENTED ? "from document" : "user reported");
		}
		return String.join(" · ", parts);
	}

	private void heading(String title) throws IOException {
		gap(10);
		ensure(40);
		text(bold, 13, title, 0);
		gap(2);
	}

	/** The bullet goes on the paragraph's first line, so space for that line is made first. */
	private void bullet(String line) throws IOException {
		float size = 10.5f;
		ensure(size * 1.4f);
		stream.beginText();
		stream.setFont(regular, size);
		stream.newLineAtOffset(MARGIN + 3, y - size);
		stream.showText("•");
		stream.endText();
		text(regular, size, line, 14);
	}

	/** Wraps and writes a paragraph, starting new pages as needed. */
	private void text(PDType0Font font, float size, String raw, float indent) throws IOException {
		float width = PDRectangle.A4.getWidth() - 2 * MARGIN - indent;
		float leading = size * 1.4f;
		for (String line : wrap(font, size, safe(font, raw), width)) {
			ensure(leading);
			y -= leading;
			stream.beginText();
			stream.setFont(font, size);
			stream.newLineAtOffset(MARGIN + indent, y + leading - size);
			stream.showText(line);
			stream.endText();
		}
	}

	private List<String> wrap(PDType0Font font, float size, String text, float width) throws IOException {
		List<String> lines = new ArrayList<>();
		StringBuilder line = new StringBuilder();
		for (String word : text.split(" ")) {
			String candidate = line.isEmpty() ? word : line + " " + word;
			if (width(font, size, candidate) <= width) {
				line.setLength(0);
				line.append(candidate);
				continue;
			}
			if (!line.isEmpty()) {
				lines.add(line.toString());
				line.setLength(0);
			}
			// A single word wider than the line is broken by characters.
			StringBuilder piece = new StringBuilder();
			for (int cp : word.codePoints().toArray()) {
				String next = piece + Character.toString(cp);
				if (width(font, size, next) > width && !piece.isEmpty()) {
					lines.add(piece.toString());
					piece.setLength(0);
				}
				piece.appendCodePoint(cp);
			}
			line.append(piece);
		}
		if (!line.isEmpty() || lines.isEmpty()) {
			lines.add(line.toString());
		}
		return lines;
	}

	private static float width(PDType0Font font, float size, String text) throws IOException {
		return font.getStringWidth(text) / 1000 * size;
	}

	/**
	 * One line of plain text the font can draw: whitespace becomes single spaces, control characters
	 * go, and characters the font lacks become "?" rather than failing the export.
	 */
	private String safe(PDType0Font font, String raw) {
		Map<Integer, Boolean> known = glyphs.computeIfAbsent(font, ignored -> new HashMap<>());
		StringBuilder out = new StringBuilder();
		String text = raw == null ? "" : raw.replaceAll("\\s+", " ").strip();
		text.codePoints().forEach(cp -> {
			if (Character.isISOControl(cp)) {
				return;
			}
			boolean drawable = known.computeIfAbsent(cp, c -> {
				try {
					font.encode(Character.toString(c));
					return true;
				}
				catch (IOException | IllegalArgumentException ex) {
					return false;
				}
			});
			out.append(drawable ? Character.toString(cp) : "?");
		});
		return out.toString();
	}

	private void gap(float points) {
		y -= points;
	}

	private void ensure(float needed) throws IOException {
		if (y - needed < MARGIN + FOOTER) {
			stream.close();
			newPage();
		}
	}

	private void newPage() throws IOException {
		PDPage page = new PDPage(PDRectangle.A4);
		document.addPage(page);
		pages.add(page);
		stream = new PDPageContentStream(document, page);
		y = PDRectangle.A4.getHeight() - MARGIN;
	}

	private void footers() throws IOException {
		for (int i = 0; i < pages.size(); i++) {
			try (PDPageContentStream footer = new PDPageContentStream(document, pages.get(i),
					PDPageContentStream.AppendMode.APPEND, true)) {
				footer.beginText();
				footer.setFont(regular, 8);
				footer.newLineAtOffset(MARGIN, MARGIN - 2);
				footer.showText(LABEL + " AI-generated.");
				footer.newLineAtOffset(0, -11);
				footer.showText("Page " + (i + 1) + " of " + pages.size());
				footer.endText();
			}
		}
	}

	private static byte[] font(String name) {
		try (InputStream in = SummaryPdf.class.getResourceAsStream("/fonts/" + name)) {
			if (in == null) {
				throw new IllegalStateException("Missing font " + name);
			}
			return in.readAllBytes();
		}
		catch (IOException ex) {
			throw new UncheckedIOException(ex);
		}
	}

}
